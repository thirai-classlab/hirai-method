#!/usr/bin/env bash
# UserPromptSubmit hook
#
# 各ターン応答で「Why × 5 階層」「現在行っていること」「他の選択肢を取らなかった理由」
# の 3 点表示をメインエージェントに強制する。
#
# 仕組み:
#   - Claude Code の UserPromptSubmit hook は stdin に { "prompt": "..." } を受け取り、
#     stdout に出力したテキストをユーザプロンプトに追加コンテキストとして注入する。
#   - 本 hook は stdin を破棄し、固定の <system-reminder> を出力するだけの単純実装。
#
# 環境変数:
#   HC_WHY_X5_DISABLE=1  ... 一時無効化（雑談セッション等で off にする）
#
# 失敗時の挙動:
#   - exit 0 のみ。失敗してもユーザターンをブロックしない（reminder 注入失敗 ≠ ブロック）。

set -euo pipefail

# stdin を必ず消費（消費しないと caller が pipe block する可能性がある）
cat > /dev/null 2>&1 || true

# 環境変数で無効化されている場合は何も出さない
if [ "${HC_WHY_X5_DISABLE:-0}" = "1" ]; then
  exit 0
fi

cat <<'EOF'
<system-reminder>
このターンの応答では、作業ステップごとに必ず以下の 3 点を明示してください。
省略・要約・「重要なものだけ表示」は不可。雑談・短い確認応答にも適用します。
詳細規範: `.claude/rules/why-x5-output.md` (2026-05-13 全面改訂)。

1. **Why × N 階層 (N ≥ 3、浅い 5 層は禁止)** — user の本来の要求 (top) と直接作業 (bottom) の因果連鎖で表示
   - **Why N (最上位)**: user の今ターンの要求 / 要件 / 事業価値の根 (可能なら user の逐語 quote)
   - **Why 1 (最下位)**: 直接作業が解決する具体問い (今呼び出す tool / 編集する file の単位)
   - **中間層**: 上位から下位への因果連鎖を 1 段ずつ降りる (並列言い換え禁止、各層が「なぜそれが上位を解決するのか」の論理 step)
   - 層数は柔軟 (3 層でも 7 層でも可、5 厳守ではない)
   - 「累積価値」「信頼性」「事業価値」「正確性」等の generic 終着は浅さのサイン — そこで止めず user の今 ask に効く理由まで書く

2. **現在行っていること** — **「なになにのためになになにを行っている」** format で書く (目的 + 直接作業の 2 要素 1 文)
   - 良い例: 「user feedback を永続化するため、`feedback_*.md` を Write している」
   - 禁止例: 「`feedback_*.md` を Write する」 (目的が含まれない単独動詞)

3. **他の選択肢を取らなかった理由** — 検討した代替案を 2 つ以上挙げ、各「なぜ採用しなかったか」を **user の今ターン要求とのズレ** として説明
   - 良い例: 「subagent 委譲 — user の今 ask は『format 是正』であり overhead で意図と乖離」
   - 禁止例: 「subagent 委譲 — 規範違反」「効率低下」 (generic、user 要求との関連未明)

出力前 self-check:
- [ ] Why N に user の今ターン要求 (or 直接派生) が書かれているか?
- [ ] 各 Why が因果連鎖か (並列言い換えではないか)?
- [ ] Why 1 が tool 呼出 / file 編集の具体単位まで降りているか?
- [ ] 「現在行っていること」が「なになにのためになになにを行っている」format か?
- [ ] 「他の選択肢」の非採用理由が user 要求とのズレ説明か? (generic 理由のみではないか?)

注意:
- ツール呼び出しの前にこの 3 点を必ず先出しすること (事後ではなく事前)
- 連続して同種の操作を行うときは、まとめてではなくステップ毎に表示すること
</system-reminder>
EOF

exit 0
