#!/usr/bin/env bash
# UserPromptSubmit hook
#
# 各ターン応答で 4 セクション (【システムの存在意義】【whyN】【現在行っていること】【他の選択肢を取らない理由】)
# format と思考ロジック (何 → 選択肢 → 選定) をメインエージェントに強制する。
# v9 (2026-05-14)。
#
# 仕組み:
#   - Claude Code の UserPromptSubmit hook は stdin に { "prompt": "..." } を受け取り、
#     stdout に出力したテキストをユーザプロンプトに追加コンテキストとして注入する。
#   - 本 hook は stdin を破棄し、固定の <system-reminder> を出力するだけの単純実装。
#
# 環境変数:
#   HC_WHY_X5_DISABLE=1  ... 一時無効化（雑談セッション等で off にする）
#
# 失敗時の挙動:
#   - exit 0 のみ。失敗してもユーザターンをブロックしない。

set -euo pipefail

# stdin を必ず消費（消費しないと caller が pipe block する可能性がある）
cat > /dev/null 2>&1 || true

# 環境変数で無効化されている場合は何も出さない
if [ "${HC_WHY_X5_DISABLE:-0}" = "1" ]; then
  exit 0
fi

cat <<'EOF'
<system-reminder>
このターンの応答では、作業ステップごとに必ず以下の 4 セクションを順番に明示してください。
省略・要約・「重要なものだけ表示」は不可。雑談・短い確認応答にも適用します。
詳細規範: `.claude/rules/why-x5-output.md` (v9, 2026-05-14)。

【システムの存在意義】
- 1 行で本作業が貢献するシステム / 事業の存在意義 / 目的

【whyN】 (複数)
- 【why1】【why2】... の連番セクション
- システムの存在意義から現在の作業に向かう因果連鎖の中間階層
- 各行は 1 段下の why を実現する上位 why (並列言い換え禁止)
- セクション数 case-by-case

【現在行っていること】
- 1 行で今呼び出す tool / 編集する file / 1 ステップ

【他の選択肢を取らない理由】
- 代替案を 3 件以上 矢印 format で
- format: 選択肢N: <内容> -> <非採用理由 (目的 / user 意図とのズレで具体)>

思考ロジック (必須、可視化と同等以上に重要):
1. 何をしないといけないのか = システム意義 → whyN → 現在の作業 まで降りる
2. どんな選択肢があるのか = 代替案 3 件以上洗い出す
3. 選定 = 各代替案を「取らない理由」として具体に書く

出力前 self-check:
- [ ] 4 セクション全て書かれているか
- [ ] 順序が システム意義 → whyN → 現在の作業 → 他選択肢 か
- [ ] 【whyN】各行が 1 段下の上位 why か (並列言い換えでないか)
- [ ] 【他の選択肢】が 3 件以上で各理由が具体か (generic 不可)
- [ ] 思考ロジック (何 → 選択肢 → 選定) を頭の中で踏んだか

注意:
- ツール呼び出しの前にこの 4 セクションを必ず先出しすること
- 連続して同種の操作はステップ毎に表示
</system-reminder>
EOF

exit 0
